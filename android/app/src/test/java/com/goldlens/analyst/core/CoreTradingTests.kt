package com.goldlens.analyst.core

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.math.sin

class CoreTradingTests {
    private fun parityCandles(count: Int = 260): List<Candle> = (0 until count).map { i ->
        val close = 2000.0 + 0.35 * i + sin(i * 0.17) * 4.0 + sin(i * 0.043) * 7.0
        val open = close - sin(i * 0.31) * 0.7
        val high = maxOf(open, close) + 0.6 + (i % 5) * 0.03
        val low = minOf(open, close) - 0.5 - (i % 3) * 0.02
        Candle(1_735_689_600_000L + i * 3_600_000L, open, high, low, close, 100.0 + i)
    }

    @Test fun indicatorsMatchPythonPandasReferenceFixture() {
        // Expected values generated by backend/indicators/calculations.py for the same 260 candles.
        val last = TechnicalIndicators.calculate(parityCandles()).last()
        assertClose(2079.4814258971396, last.ema20!!)
        assertClose(2077.4470049002466, last.ema50!!)
        assertClose(2071.323803689155, last.ema100!!)
        assertClose(2057.7344452485427, last.ema200!!)
        assertClose(82.28384103798555, last.rsi14!!)
        assertClose(1.117835546596325, last.macd!!)
        assertClose(0.4394884488432128, last.macdSignal!!)
        assertClose(0.6783470977531122, last.macdHistogram!!)
        assertClose(1.8133796342307025, last.atr14!!)
        assertClose(2078.442692628703, last.bollingerMiddle!!)
        assertClose(2082.901875525794, last.bollingerUpper!!)
        assertClose(2073.983509731612, last.bollingerLower!!)
        assertClose(86.2552583235026, last.stochasticK!!)
        assertClose(85.01488111914851, last.stochasticD!!)
    }

    @Test fun warmupValuesAreNotInvented() {
        val result = TechnicalIndicators.calculate(parityCandles(20))
        assertNull(result[18].ema20)
        assertTrue(result.last().ema20 != null)
        assertNull(result.last().ema200)
        assertTrue(result.last().atr14 != null)
    }

    @Test fun normalizationRejectsInvalidRowsAndKeepsLastDuplicate() {
        val valid = parityCandles(3)
        val replacement = valid[1].copy(close = valid[1].close + 0.05, high = valid[1].high + 0.05)
        val invalid = valid[0].copy(high = valid[0].low - 1)
        val normalized = normalizeCandles(listOf(valid[1], valid[0], replacement, invalid, valid[2]))
        assertEquals(3, normalized.size)
        assertEquals(replacement.close, normalized[1].close, 0.0)
        assertTrue(normalized.zipWithNext().all { it.second.timestampMillis > it.first.timestampMillis })
    }

    @Test fun csvImportHandlesHeaderOrderQuotedValuesAndReportsBadRows() {
        val csv = """timestamp,open,high,low,close,volume
"2025-01-01T02:00:00Z",102,104,101,103,10
2025-01-01T00:00:00Z,100,102,99,101,1000
not-a-time,1,2,0.5,1.5,3
"""
        val parsed = CsvCandleParser.parse(csv)
        assertEquals(2, parsed.candles.size)
        assertEquals(1, parsed.skippedRows)
        assertTrue(parsed.candles.zipWithNext().all { it.second.timestampMillis > it.first.timestampMillis })
        assertClose(1000.0, parsed.candles.first().volume)
    }

    @Test fun riskCalculationUsesUserBrokerContractAndChecksInputs() {
        val result = RiskInput(
            accountBalance = 10_000.0, riskPercent = 1.0, entry = 2_000.0,
            stopLoss = 1_990.0, takeProfit = 2_020.0, contractSize = 100.0,
        ).calculate()
        assertClose(100.0, result.riskAmount)
        assertClose(1_000.0, result.riskPerLot)
        assertClose(0.1, result.positionLots)
        assertClose(200.0, result.potentialProfit)
        assertClose(2.0, result.rewardRisk)
        assertTrue(runCatching { RiskInput(1_000.0, 10.0, 2000.0, 1990.0, 2020.0).calculate() }.isFailure)
        assertTrue(runCatching { RiskInput(1_000.0, 1.0, 2000.0, 2000.0, 2020.0).calculate() }.isFailure)
    }

    @Test fun staleLiveDataReturnsWaitButImportedHistoryCanBeAnalysed() {
        val old = parityCandles().map { it.copy(timestampMillis = it.timestampMillis - 90L * 24 * 60 * 60 * 1000) }
        val live = MarketDataset(old, DataSourceKind.LIVE, "test feed", "1h", 0)
        val imported = live.copy(source = DataSourceKind.IMPORTED_CSV, sourceLabel = "local csv")
        val liveResult = AnalysisEngine.analyze(live, nowMillis = old.last().timestampMillis + 60L * 24 * 60 * 60 * 1000)
        val importedResult = AnalysisEngine.analyze(imported, nowMillis = old.last().timestampMillis + 60L * 24 * 60 * 60 * 1000)
        assertEquals(Direction.WAIT, liveResult.direction)
        assertTrue(liveResult.reason.contains("stale"))
        assertFalse(importedResult.reason.contains("stale"))
    }

    @Test fun repeatedPivotTouchesClusterIntoStrongZonesAndCurrentBarDoesNotLookAhead() {
        val candles = repeatedLevelCandles()
        val zones = SupportResistanceDetector.detect(candles, "1h", leftBars = 2, rightBars = 2)
        val resistance = zones.first { it.side == ZoneSide.RESISTANCE && it.midpoint in 109.0..111.0 }
        val support = zones.first { it.side == ZoneSide.SUPPORT && it.midpoint in 89.0..91.0 }
        assertTrue(resistance.touches >= 3)
        assertTrue(support.touches >= 3)
        assertEquals("strong", resistance.strength)
        assertEquals("strong", support.strength)
        val unfinishedLastPivot = candles.dropLast(1) + candles.last().copy(high = 120.0)
        val noFutureConfirmation = SupportResistanceDetector.detect(unfinishedLastPivot, "1h")
        assertFalse(noFutureConfirmation.any { it.midpoint > 115.0 })
    }

    @Test fun candleCloseMustBreakZoneAndReturnForRetest() {
        val base = repeatedLevelCandles()
        val resistanceZones = SupportResistanceDetector.detect(base, "1h")
        val zone = resistanceZones.first { it.side == ZoneSide.RESISTANCE && it.midpoint in 109.0..111.0 }
        val wickOnly = base + candle(30, open = 109.8, high = zone.upper + 2, low = 108.8, close = zone.midpoint - 0.1)
        val wickZones = SupportResistanceDetector.detect(wickOnly, "1h")
        assertEquals(ZoneStatus.ACTIVE, wickZones.first { it.side == ZoneSide.RESISTANCE && it.midpoint in 109.0..111.0 }.status)

        val confirmedBreak = base + candle(30, 111.5, 113.0, 111.0, 112.0)
        val broken = SupportResistanceDetector.detect(confirmedBreak, "1h")
            .first { it.side == ZoneSide.RESISTANCE && it.midpoint in 109.0..111.0 }
        assertEquals(ZoneStatus.BROKEN, broken.status)

        val retest = confirmedBreak + candle(31, 111.2, 112.0, 110.2, 111.0)
        val retested = SupportResistanceDetector.detect(retest, "1h")
            .first { it.side == ZoneSide.RESISTANCE && it.midpoint in 109.0..111.0 }
        assertEquals(ZoneStatus.RETESTING, retested.status)
    }

    private fun repeatedLevelCandles(): List<Candle> {
        val closes = listOf(100.0, 103.0, 106.0, 108.0, 107.0, 104.0, 100.0, 96.0, 93.0, 95.0,
            99.0, 104.0, 107.0, 108.0, 106.0, 102.0, 97.0, 93.0, 92.0, 96.0,
            101.0, 105.0, 108.0, 107.0, 103.0, 98.0, 94.0, 92.0, 95.0, 100.0)
        return closes.mapIndexed { index, close ->
            var high = close + 0.2
            var low = close - 0.2
            if (index in setOf(3, 12, 22)) high = 110.0
            if (index in setOf(8, 18, 27)) low = 90.0
            candle(index.toLong(), close, high, low, close)
        }
    }

    private fun candle(index: Long, open: Double, high: Double, low: Double, close: Double) =
        Candle(1_735_689_600_000L + index * 3_600_000L, open, high, low, close)

    private fun assertClose(expected: Double, actual: Double, tolerance: Double = 1e-7) =
        assertEquals(expected, actual, tolerance)
}
